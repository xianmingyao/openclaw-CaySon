# -*- coding: utf-8 -*-
"""
图数 → (横向X, 纵向Y) 偏移计算器（嵌套循环版）
================================================

数据点（图数 : X , Y）：
    10 :  635 ,   0
     9 :  675 ,  -5
     8 :  720 ,  -5
     7 :  780 ,  -5
     6 :  840 ,  -5
     5 :  920 ,  -5
     4 :  980 ,  -5
     3 : 1060 ,  -5

横向 X 差值（10→9, 9→8, ...）：
     40,  45,  60,  60,  80,  60,  80
                              ^^   ^^
                              这两步不太规整（可能是手测误差）

纵向 Y 差值：
    -5, 0, 0, 0, 0, 0, 0, 0, 0
    → 10→9 时跳 -5，之后稳定

外推规则（n < 3）：
    X 步长按 +100, +100 递增
    Y 保持 -5
"""

# 横向 X 步长（索引 i 表示第 i 步，10→9 是 i=0）
X_STEPS = [40, 45, 60, 60, 80, 60, 80, 100, 100]

# 纵向 Y 步长
Y_STEPS = [-5, 0, 0, 0, 0, 0, 0, 0, 0]


def calc_offset(n: int):
    """根据图数 n 计算 (X, Y) 偏移（内层累加步长）"""
    x, y = 635, 0
    for i in range(10 - n):  # 内层：累加 0 ~ (10-n-1) 步
        x += X_STEPS[i]
        y += Y_STEPS[i]
    return x, y


def main():
    # 外层：图数从 10 遍历到 1
    print(f"{'图数':<6} {'横向X':<8} {'纵向Y':<8} {'备注'}")
    print("-" * 40)
    for n in range(10, 0, -1):
        x, y = calc_offset(n)
        note = "已知" if n >= 3 else "🟡 外推"
        print(f"{n:<6} {x:<8} {y:<8} {note}")

    # 验证：横向 X 单步增量
    print("\n横向 X 步长检查：")
    for i, step in enumerate(X_STEPS):
        print(f"  第 {i} 步（n={10-i}→{9-i}）: +{step}")


if __name__ == "__main__":
    main()
